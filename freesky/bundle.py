"""Packs a task into a self-contained driver script.

Every provider runs the same thing: one Python file that carries the workdir as an
embedded tar.gz (or reads it from a file next to it), unpacks it, runs `setup` and
`run` with bash, then packs the declared outputs into `fgpu_out.tgz` together with
`fgpu_result.json` (exit code, timings) and the full log. This keeps adapters thin:
they only need to "upload one file, run python on it, download one file".
"""
from __future__ import annotations

import base64
import io
import json
import os
import tarfile

from .spec import Task

MAX_EMBED_BYTES = 30 * 1024 * 1024  # bigger workdirs should ship data elsewhere (HF, dataset, URL)
EXCLUDE_DIRS = {".git", "__pycache__", ".venv", "venv", "node_modules", ".fgpu"}
RESULT_TGZ = "fgpu_out.tgz"

DRIVER = r'''#!/usr/bin/env python3
# generated by freesky - runs one task and packs its outputs
import base64, io, json, os, subprocess, sys, tarfile, time

PAYLOAD = "__PAYLOAD__"
SPEC = json.loads(base64.b64decode("__SPEC__").decode())
BASE = os.environ.get("FGPU_BASE") or SPEC.get("base") or os.getcwd()
WORK = os.path.join(BASE, "fgpu_work")
OUT = os.path.join(BASE, "__RESULT_TGZ__")


def main():
    t0 = time.time()
    os.makedirs(WORK, exist_ok=True)
    payload = PAYLOAD
    if payload == "FILE":  # uploaded separately, next to the base dir (works in Jupyter kernels too)
        with open(SPEC.get("payload_path") or os.path.join(BASE, "fgpu_payload.tgz"), "rb") as f:
            data = f.read()
    else:
        data = base64.b64decode(payload)
    with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as tar:
        try:
            tar.extractall(WORK, filter="data")
        except TypeError:  # python < 3.12
            tar.extractall(WORK)
    env = dict(os.environ, **SPEC.get("env", {}))
    env["FGPU_PROVIDER"] = SPEC.get("provider", "")
    log_path = os.path.join(WORK, "fgpu.log")
    code, phases = 0, {}
    with open(log_path, "w") as log:
        for phase in ("setup", "run"):
            cmd = SPEC.get(phase) or ""
            if not cmd.strip():
                continue
            ts = time.time()
            print(f"[fgpu] {phase}: {cmd}", flush=True)
            p = subprocess.Popen(["bash", "-lc", cmd], cwd=WORK, env=env,
                                 stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
            for line in p.stdout:
                sys.stdout.write(line)
                log.write(line)
            code = p.wait()
            phases[phase] = round(time.time() - ts, 1)
            if code != 0:
                print(f"[fgpu] {phase} fallito con codice {code}", flush=True)
                break
    gpu = ""
    try:
        gpu = subprocess.run(["nvidia-smi", "--query-gpu=name", "--format=csv,noheader"],
                             capture_output=True, text=True, timeout=20).stdout.strip()
    except Exception:
        pass
    result = {"exit_code": code, "seconds": round(time.time() - t0, 1), "phases": phases,
              "gpu": gpu, "provider": SPEC.get("provider", "")}
    with tarfile.open(OUT, "w:gz") as tar:
        for rel in SPEC.get("outputs", []):
            p = os.path.join(WORK, rel)
            if os.path.exists(p):
                tar.add(p, arcname=os.path.join("outputs", rel))
        tar.add(log_path, arcname="fgpu.log")
        blob = json.dumps(result).encode()
        info = tarfile.TarInfo("fgpu_result.json")
        info.size = len(blob)
        tar.addfile(info, io.BytesIO(blob))
    print("[fgpu] RESULT " + json.dumps(result), flush=True)
    return code


if __name__ == "__main__":
    rc = main()
    if SPEC.get("exit_with_code", True):
        sys.exit(rc)
'''


def pack_workdir(path: str) -> bytes:
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as tar:
        for root, dirs, files in os.walk(path):
            dirs[:] = sorted(d for d in dirs if d not in EXCLUDE_DIRS)
            for name in sorted(files):
                full = os.path.join(root, name)
                tar.add(full, arcname=os.path.relpath(full, path))
    return buf.getvalue()


def make_driver(task: Task, provider: str, base: str = "", embed: bool = True,
                exit_with_code: bool = True, payload_path: str = "") -> tuple[str, bytes]:
    """Returns (driver_source, payload_tgz). With embed=True the payload is inside the source,
    otherwise the driver reads it from `payload_path` (default: <base>/fgpu_payload.tgz)."""
    payload = pack_workdir(task.workdir_path)
    if embed and len(payload) > MAX_EMBED_BYTES:
        raise ValueError(f"workdir di {len(payload) // 1024 // 1024} MB: troppo grande da incorporare "
                         f"(max {MAX_EMBED_BYTES // 1024 // 1024} MB). Scarica i dati dentro 'setup'.")
    spec = {"setup": task.setup, "run": task.run, "outputs": task.outputs, "env": task.env,
            "provider": provider, "base": base, "exit_with_code": exit_with_code,
            "payload_path": payload_path}
    src = (DRIVER
           .replace("__SPEC__", base64.b64encode(json.dumps(spec).encode()).decode())
           .replace("__RESULT_TGZ__", RESULT_TGZ)
           .replace("__PAYLOAD__", base64.b64encode(payload).decode() if embed else "FILE"))
    return src, payload


def unpack_result(tgz_path: str, dest: str) -> dict:
    """Extracts outputs/ and the log into dest, returns fgpu_result.json."""
    os.makedirs(dest, exist_ok=True)
    result = {}
    with tarfile.open(tgz_path, "r:gz") as tar:
        for m in tar.getmembers():
            if m.name == "fgpu_result.json":
                result = json.load(tar.extractfile(m))
                continue
            if m.name.startswith("/") or ".." in m.name.split("/"):
                continue
            try:
                tar.extract(m, dest, filter="data")
            except TypeError:
                tar.extract(m, dest)
    return result
