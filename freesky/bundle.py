"""Packs a task into one self-contained driver script that every provider runs.

The driver carries the workdir as an embedded tar.gz (or reads it from a file next to
it), unpacks it, runs `setup` and `run` with bash, then packs the declared outputs, the
checkpoint directory, the log and `fgpu_result.json` into `fgpu_out.tgz`. Adapters only
need to "upload one file, run python on it, download one file".

Long jobs: the driver enforces a per-segment deadline (the provider's session limit).
When it is reached the job's process group gets SIGTERM, then SIGKILL after a grace
period; the checkpoint dir is still packed, so the next segment can resume anywhere.
Services: with mode=serve the driver runs `setup`, then `run` in the foreground forever.
"""
from __future__ import annotations

import base64
import io
import json
import os
import tarfile

from .spec import Task

MAX_EMBED_BYTES = 30 * 1024 * 1024
EXCLUDE_DIRS = {".git", "__pycache__", ".venv", "venv", "node_modules", ".fgpu", "freesky-runs"}
RESULT_TGZ = "fgpu_out.tgz"

DRIVER = r'''#!/usr/bin/env python3
# generated by freesky - runs one task segment and packs its outputs
import base64, io, json, os, signal, subprocess, sys, tarfile, threading, time

PAYLOAD = "__PAYLOAD__"
SPEC = json.loads(base64.b64decode("__SPEC__").decode())
BASE = os.environ.get("FGPU_BASE") or SPEC.get("base") or os.getcwd()
WORK = os.path.join(BASE, "fgpu_work")
OUT = os.path.join(BASE, "__RESULT_TGZ__")


def unpack():
    os.makedirs(WORK, exist_ok=True)
    if PAYLOAD == "FILE":  # uploaded separately (works inside Jupyter kernels too)
        with open(SPEC.get("payload_path") or os.path.join(BASE, "fgpu_payload.tgz"), "rb") as f:
            data = f.read()
    else:
        data = base64.b64decode(PAYLOAD)
    with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as tar:
        try:
            tar.extractall(WORK, filter="data")
        except TypeError:  # python < 3.12
            tar.extractall(WORK)


CHILD = {"p": None}


def forward_signal(signum, frame):
    """Stopping the driver stops the whole job: forward the signal to the job's process group."""
    p = CHILD["p"]
    if p is not None and p.poll() is None:
        try:
            os.killpg(p.pid, signum)
            p.wait(timeout=SPEC.get("grace_s", 120))
        except Exception:
            try:
                os.killpg(p.pid, signal.SIGKILL)
            except Exception:
                pass
    sys.exit(128 + signum)


def run_phase(cmd, env, log, deadline):
    """Runs cmd in its own process group; enforces the deadline. Returns (code, hit_deadline)."""
    p = subprocess.Popen(["bash", "-lc", cmd], cwd=WORK, env=env, stdout=subprocess.PIPE,
                         stderr=subprocess.STDOUT, text=True, start_new_session=True)
    CHILD["p"] = p
    hit = {"v": False}

    def watchdog():
        while p.poll() is None:
            if deadline and time.time() >= deadline:
                hit["v"] = True
                print("[fgpu] segment deadline reached: SIGTERM (save your checkpoint now)", flush=True)
                try:
                    os.killpg(p.pid, signal.SIGTERM)
                except ProcessLookupError:
                    return
                grace_end = time.time() + SPEC.get("grace_s", 120)
                while p.poll() is None and time.time() < grace_end:
                    time.sleep(1)
                if p.poll() is None:
                    os.killpg(p.pid, signal.SIGKILL)
                return
            time.sleep(0.5)

    threading.Thread(target=watchdog, daemon=True).start()
    for line in p.stdout:
        sys.stdout.write(line)
        sys.stdout.flush()
        if log:
            log.write(line)
            log.flush()
    return p.wait(), hit["v"]


def main():
    t0 = time.time()
    for sig in (signal.SIGTERM, signal.SIGINT, signal.SIGHUP):
        try:
            signal.signal(sig, forward_signal)
        except (ValueError, OSError):  # not in the main thread (e.g. some notebook kernels)
            pass
    unpack()
    env = dict(os.environ, **SPEC.get("env", {}))
    env["FGPU_PROVIDER"] = SPEC.get("provider", "")
    env["FREESKY_PROVIDER"] = SPEC.get("provider", "")
    env["FREESKY_SEGMENT"] = str(SPEC.get("segment", 1))
    ckpt = SPEC.get("checkpoint")
    if ckpt:
        cdir = os.path.join(WORK, ckpt)
        env["FREESKY_RESUME"] = "1" if os.path.isdir(cdir) and os.listdir(cdir) else "0"
        os.makedirs(cdir, exist_ok=True)
        env["FREESKY_CHECKPOINT_DIR"] = cdir
    deadline = t0 + SPEC["deadline_s"] if SPEC.get("deadline_s") else None

    if SPEC.get("mode") == "serve":
        for phase in ("setup", "run"):
            if (SPEC.get(phase) or "").strip():
                print(f"[fgpu] {phase}: {SPEC[phase]}", flush=True)
                code, _ = run_phase(SPEC[phase], env, None, None)
                if code != 0:
                    return code
        return 0

    log_path = os.path.join(WORK, "fgpu.log")
    code, phases, hit = 0, {}, False
    with open(log_path, "w") as log:
        for phase in ("setup", "run"):
            cmd = SPEC.get(phase) or ""
            if not cmd.strip():
                continue
            ts = time.time()
            print(f"[fgpu] {phase}: {cmd}", flush=True)
            code, hit = run_phase(cmd, env, log, deadline)
            phases[phase] = round(time.time() - ts, 1)
            if hit or code != 0:
                if not hit:
                    print(f"[fgpu] {phase} failed with exit code {code}", flush=True)
                break
    gpu = ""
    try:
        gpu = subprocess.run(["nvidia-smi", "--query-gpu=name", "--format=csv,noheader"],
                             capture_output=True, text=True, timeout=20).stdout.strip()
    except Exception:
        pass
    result = {"exit_code": code, "deadline_hit": hit, "seconds": round(time.time() - t0, 1),
              "phases": phases, "gpu": gpu, "provider": SPEC.get("provider", ""),
              "segment": SPEC.get("segment", 1)}
    with tarfile.open(OUT, "w:gz") as tar:
        for rel in SPEC.get("outputs", []) + ([ckpt] if ckpt else []):
            p = os.path.join(WORK, rel)
            if os.path.exists(p):
                tar.add(p, arcname=os.path.join("outputs", rel))
        tar.add(log_path, arcname="fgpu.log")
        blob = json.dumps(result).encode()
        info = tarfile.TarInfo("fgpu_result.json")
        info.size = len(blob)
        tar.addfile(info, io.BytesIO(blob))
    print("[fgpu] RESULT " + json.dumps(result), flush=True)
    return code


if __name__ == "__main__":
    rc = main()
    if SPEC.get("exit_with_code", True):
        sys.exit(rc)
'''


def pack_workdir(path: str) -> bytes:
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as tar:
        for root, dirs, files in os.walk(path):
            dirs[:] = sorted(d for d in dirs if d not in EXCLUDE_DIRS)
            for name in sorted(files):
                full = os.path.join(root, name)
                tar.add(full, arcname=os.path.relpath(full, path))
    return buf.getvalue()


def make_driver(task: Task, provider: str, base: str = "", embed: bool = True,
                exit_with_code: bool = True, payload_path: str = "", deadline_s: int = 0,
                segment: int = 1, mode: str = "batch", grace_s: int = 120) -> tuple[str, bytes]:
    """Returns (driver_source, payload_tgz). With embed=True the payload is inside the source,
    otherwise the driver reads it from `payload_path` (default: <base>/fgpu_payload.tgz)."""
    payload = pack_workdir(task.workdir_path)
    if embed and len(payload) > MAX_EMBED_BYTES:
        raise ValueError(f"workdir is {len(payload) // 1024 // 1024} MB, too big to embed "
                         f"(max {MAX_EMBED_BYTES // 1024 // 1024} MB): download big data in `setup`")
    spec = {"setup": task.setup, "run": task.run, "outputs": task.outputs, "env": task.env,
            "provider": provider, "base": base, "exit_with_code": exit_with_code,
            "payload_path": payload_path, "checkpoint": task.checkpoint, "deadline_s": deadline_s,
            "segment": segment, "mode": mode, "grace_s": grace_s}
    src = (DRIVER
           .replace("__SPEC__", base64.b64encode(json.dumps(spec).encode()).decode())
           .replace("__RESULT_TGZ__", RESULT_TGZ)
           .replace("__PAYLOAD__", base64.b64encode(payload).decode() if embed else "FILE"))
    return src, payload


def unpack_result(tgz_path: str, dest: str) -> dict:
    """Extracts outputs/ and the log into dest, returns fgpu_result.json."""
    os.makedirs(dest, exist_ok=True)
    result = {}
    with tarfile.open(tgz_path, "r:gz") as tar:
        for m in tar.getmembers():
            if m.name == "fgpu_result.json":
                result = json.load(tar.extractfile(m))
                continue
            if m.name.startswith("/") or ".." in m.name.split("/"):
                continue
            try:
                tar.extract(m, dest, filter="data")
            except TypeError:
                tar.extract(m, dest)
    return result
